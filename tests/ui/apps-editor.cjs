const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {setup}=require('./application-fixtures.cjs');
const base=process.env.DIGUP_UI_URL||'http://127.0.0.1:8765';
let browser;
(async()=>{
  browser=await chromium.launch({executablePath:process.env.DIGUP_CHROME||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:660,height:620}}),errors=[];
  page.on('pageerror',e=>{errors.push(e.message);console.error(e.stack);});await setup(page);
  await page.addInitScript(()=>{
    const old=window.__TAURI__.core.invoke;
    window.__TAURI__.core.invoke=async(c,a)=>{if(c==='search_apps'&&a.q==='Application 000')await new Promise(r=>setTimeout(r,400));return old(c,a);};
  });
  await page.goto(base+'/settings.html?tab=apps');
  await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===100);
  assert.equal(await page.locator('.app-editor').count(),1);
  const rows=page.locator('.app-settings-row');
  const aliases=()=>page.locator('.app-editor textarea').nth(0),purpose=()=>page.locator('.app-editor textarea').nth(1);
  await aliases().fill('Pictures\nPhotos editor');await purpose().fill('Retouch portraits  ');
  await rows.nth(1).click();await purpose().fill('Second app draft');
  await rows.first().click();
  assert.equal(await purpose().inputValue(),'Retouch portraits  ');
  assert.equal(await aliases().inputValue(),'Pictures\nPhotos editor');
  await purpose().focus();await purpose().evaluate(el=>el.setSelectionRange(5,5));
  await page.evaluate(()=>{window.dispatchEvent(new Event('focus'));window.emit('applications',{supported:true,enabled:true,semanticEnabled:true,count:150});window.emit('applications-progress',{state:'preparing',encoder:'ready',total:150,embedded:23});});
  await page.waitForTimeout(200);
  assert.equal(await purpose().inputValue(),'Retouch portraits  ');
  assert.equal(await purpose().evaluate(el=>el.selectionStart),5);
  assert.match(await page.locator('#apps-drafts').textContent(),/2 applications/);
  await page.selectOption('#apps-visibility','hidden');
  await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===1);
  assert.match(await rows.first().textContent(),/Hidden application/);
  await page.selectOption('#apps-visibility','visible');
  await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===100);
  assert.equal(await purpose().inputValue(),'Retouch portraits  ');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.waitForFunction(()=>window.calls.some(c=>c.command==='set_app_override'));
  const saved=await page.evaluate(()=>window.calls.find(c=>c.command==='set_app_override').args);
  assert.equal(saved.value.purpose,'Retouch portraits');assert.deepEqual(saved.value.aliases,['Pictures','Photos editor']);
  await page.waitForFunction(()=>document.querySelector('.app-editor button[type=submit]').disabled);
  await rows.nth(1).click();assert.equal(await purpose().inputValue(),'Second app draft');
  await page.getByRole('button',{name:'Revert',exact:true}).click();assert.equal(await purpose().inputValue(),'');
  await rows.first().click();await page.getByRole('button',{name:'Reset overrides',exact:true}).click();
  await page.waitForFunction(()=>window.calls.filter(c=>c.command==='set_app_override').length===2);
  await page.waitForFunction(()=>document.querySelectorAll('.app-editor textarea')[1].value==='');
  await aliases().fill(Array(17).fill('alias').join('\n'));
  await page.getByRole('button',{name:'Save',exact:true}).click();
  assert.match(await page.locator('.app-editor-message').textContent(),/up to 16 aliases/);
  assert.equal(await page.evaluate(()=>window.calls.filter(c=>c.command==='set_app_override').length),2);
  await aliases().fill('😀'.repeat(80));await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.waitForFunction(()=>window.calls.filter(c=>c.command==='set_app_override').length===3);
  assert.equal([...(await page.evaluate(()=>window.calls.filter(c=>c.command==='set_app_override').at(-1).args.value.aliases[0]))].length,80);
  await page.fill('#apps-filter','Application 000');await page.waitForTimeout(150);await page.fill('#apps-filter','Application 002');
  await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===1&&document.querySelector('.app-settings-row').textContent.includes('002'));
  await page.waitForTimeout(500);assert.match(await rows.first().textContent(),/002/);
  await page.fill('#apps-filter','');await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===100);
  await page.getByRole('button',{name:'Show more applications',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.app-settings-row').length===150);
  await rows.nth(120).click();await purpose().fill('Late page draft');
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await page.waitForTimeout(250);
  assert.match(await page.locator('.app-editor-name').textContent(),/120/);
  assert.equal(await purpose().inputValue(),'Late page draft');
  await page.evaluate(()=>{window.emit('state',{model:{state:'ready'}});window.emit('applications-progress',{state:'ready',encoder:'ready',embedded:150,total:150});});
  assert.equal(await page.locator('#apps-prepare').isDisabled(),true);
  assert.equal(await page.evaluate(()=>window.calls.some(c=>c.command==='search_apps'&&c.args.meaning)),false);
  assert.deepEqual(errors,[]);
  if(process.env.DIGUP_EDITOR_SCREENSHOT){await page.locator('.settings').evaluate(el=>el.scrollTop=0);await page.screenshot({path:process.env.DIGUP_EDITOR_SCREENSHOT});}
  console.log('PASS: one editor, cross-selection drafts, caret/focus/progress retention, native visibility pagination, save/revert/reset, Unicode limits and stale queries');
  await browser.close();
})().catch(async error=>{console.error(error);if(browser)await browser.close();process.exit(1)});
